def build_regression_model(X_train, X_test, y_train, y_test):
    """Build Random Forest Regression model"""

    print(" REGRESSION MODEL (Predicting Continuous QoE)")


    rf_reg = RandomForestRegressor(n_estimators=100, max_depth=10, random_state=42, n_jobs=-1)
    rf_reg.fit(X_train, y_train)

    y_pred_train = rf_reg.predict(X_train)
    y_pred_test = rf_reg.predict(X_test)

    train_rmse = np.sqrt(mean_squared_error(y_train, y_pred_train))
    test_rmse = np.sqrt(mean_squared_error(y_test, y_pred_test))

    print(f"\nTraining RMSE: {train_rmse:.4f}")
    print(f"Testing RMSE: {test_rmse:.4f}")

    plt.figure(figsize=(10, 6))
    plt.scatter(y_test, y_pred_test, alpha=0.5)
    plt.plot([y_test.min(), y_test.max()], [y_test.min(), y_test.max()], 'r--', lw=2)
    plt.xlabel('Actual QoE')
    plt.ylabel('Predicted QoE')
    plt.title('Regression: Actual vs Predicted QoE')
    plt.tight_layout()
    plt.show()

    return rf_reg

