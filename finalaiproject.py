def main():
    """Main execution pipeline"""


    print(" AI-POWERED QoE PREDICTION & OPTIMIZATION SYSTEM")


    # Upload dataset
    df = upload_dataset()

    if df is None:
        print("\n Failed to load dataset. Please try again.")
        return

    # Configure columns
    QOE_COLUMN, QOS_COLUMNS, QOE_THRESHOLD = configure_columns(df)

    if not QOS_COLUMNS:
        print("\n No feature columns selected. Cannot proceed.")
        return


    print(" STARTING ANALYSIS PIPELINE")


    # Preprocess
    print("\n Preprocessing data...")
    df = df.dropna(thresh=len(df.columns) * 0.5)

    numerical_cols = df.select_dtypes(include=[np.number]).columns
    for col in numerical_cols:
        df[col].fillna(df[col].median(), inplace=True)

    categorical_cols = df.select_dtypes(include=['object']).columns
    for col in categorical_cols:
        df[col].fillna(df[col].mode()[0], inplace=True)

    print(f" Data cleaned. Final shape: {df.shape}")

    # Verify columns
    if QOE_COLUMN not in df.columns:
        print(f"\n QoE column '{QOE_COLUMN}' not found!")
        return

    available_qos = [col for col in QOS_COLUMNS if col in df.columns]
    if not available_qos:
        print(" No valid QoS columns found!")
        return
    QOS_COLUMNS = available_qos

    # EDA
    perform_eda(df, QOE_COLUMN, QOS_COLUMNS)

    # Prepare data
    X = df[QOS_COLUMNS].values
    y_continuous = df[QOE_COLUMN].values
    y_categorical = (y_continuous >= QOE_THRESHOLD).astype(int)

    # Encode categorical features
    le = LabelEncoder()
    for col in df.select_dtypes(include=['object']).columns:
        if col in QOS_COLUMNS:
            idx = QOS_COLUMNS.index(col)
            X[:, idx] = le.fit_transform(df[col])

    # Scale features
    scaler = StandardScaler()
    X_scaled = scaler.fit_transform(X)

    # Split data
    X_train, X_test, y_train_reg, y_test_reg = train_test_split(
        X_scaled, y_continuous, test_size=0.2, random_state=42
    )
    _, _, y_train_clf, y_test_clf = train_test_split(
        X_scaled, y_categorical, test_size=0.2, random_state=42
    )

    # Build models
    regression_model = build_regression_model(X_train, X_test, y_train_reg, y_test_reg)
    classification_model = build_classification_model(X_train, X_test, y_train_clf, y_test_clf)

    # Feature importance
    analyze_feature_importance(regression_model, QOS_COLUMNS)

    # Anomaly detection
    anomaly_labels, anomaly_model = detect_anomalies(X_scaled, contamination=0.1)

    # Q-Learning
    Q_table, optimal_policy = q_learning_optimization(episodes=500)

    # Adaptive feedback
    feedback_system = AdaptiveFeedbackSystem(
        prediction_model=regression_model,
        anomaly_detector=anomaly_model,
        qoe_threshold=QOE_THRESHOLD
    )

    adjustment_log = feedback_system.monitor_and_adapt(X_test[:100])


    print(" PIPELINE COMPLETE!")

    print("\n All 8 steps executed successfully!")
    print(" Models trained and ready for deployment")

    return {
        'regression_model': regression_model,
        'classification_model': classification_model,
        'anomaly_model': anomaly_model,
        'feedback_system': feedback_system,
        'scaler': scaler,
        'Q_table': Q_table
    }

# Run the pipeline
models = main()

