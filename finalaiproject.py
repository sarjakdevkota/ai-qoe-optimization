class AdaptiveFeedbackSystem:
    """Adaptive system that monitors QoE and triggers adjustments"""
    def __init__(self, prediction_model, anomaly_detector, qoe_threshold=3.0):
        self.prediction_model = prediction_model
        self.anomaly_detector = anomaly_detector
        self.qoe_threshold = qoe_threshold
        self.adjustment_log = []

    def monitor_and_adapt(self, network_data):
        """Monitor network data and trigger adaptive responses"""

        print(" ADAPTIVE FEEDBACK SYSTEM")


        predicted_qoe = self.prediction_model.predict(network_data)
        anomaly_flag = self.anomaly_detector.predict(network_data)

        print(f"\nMonitoring {len(network_data)} network samples...")
        print(f"Predicted QoE (mean): {np.mean(predicted_qoe):.3f}")
        print(f"Anomalies detected: {np.sum(anomaly_flag == -1)} samples")

        for i, (qoe, anomaly) in enumerate(zip(predicted_qoe, anomaly_flag)):
            if qoe < self.qoe_threshold or anomaly == -1:
                action = self._trigger_adjustment(qoe, anomaly == -1)
                self.adjustment_log.append({
                    'sample_id': i,
                    'qoe': qoe,
                    'anomaly': anomaly == -1,
                    'action': action
                })

        print(f"\nTotal Adjustments Triggered: {len(self.adjustment_log)}")

        return self.adjustment_log

    def _trigger_adjustment(self, qoe, is_anomaly):
        """Determine and log adjustment action"""
        if is_anomaly:
            return "ALERT: Anomaly detected - Investigate network issue"
        elif qoe < 2.5:
            return "ACTION: Increase bandwidth allocation"
        elif qoe < self.qoe_threshold:
            return "ACTION: Optimize network routing"
        return "MONITOR: Continue observation"

