def detect_anomalies(X, contamination=0.1):
    """Detect anomalies using Isolation Forest"""

    print("🔍 ANOMALY DETECTION")


    iso_forest = IsolationForest(contamination=contamination, random_state=42)
    anomaly_labels = iso_forest.fit_predict(X)

    n_anomalies = np.sum(anomaly_labels == -1)
    print(f"\nTotal Samples: {len(anomaly_labels)}")
    print(f"Detected Anomalies: {n_anomalies} ({n_anomalies/len(anomaly_labels)*100:.2f}%)")

    pca = PCA(n_components=2)
    X_pca = pca.fit_transform(X)

    plt.figure(figsize=(10, 6))
    plt.scatter(X_pca[anomaly_labels == 1, 0], X_pca[anomaly_labels == 1, 1],
                c='blue', label='Normal', alpha=0.5)
    plt.scatter(X_pca[anomaly_labels == -1, 0], X_pca[anomaly_labels == -1, 1],
                c='red', label='Anomaly', alpha=0.7)
