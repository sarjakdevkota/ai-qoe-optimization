class QoEEnvironment:
    """Simple environment for RL-based QoE optimization"""
    def __init__(self, initial_qoe=3.0):
        self.qoe = initial_qoe
        self.state = 0

    def reset(self):
        self.qoe = 3.0
        self.state = 2
        return self.state

    def step(self, action):
        if action == 0:
            self.qoe -= 0.3
        elif action == 2:
            self.qoe += 0.5

        self.qoe += np.random.normal(0, 0.1)
        self.qoe = np.clip(self.qoe, 1.0, 5.0)

        self.state = int((self.qoe - 1) / 0.8)
        self.state = np.clip(self.state, 0, 4)

        reward = self.qoe - 3.0
        done = False

        return self.state, reward, done

def q_learning_optimization(episodes=1000):
    """Q-Learning for dynamic QoE optimization"""

    print(" REINFORCEMENT LEARNING (Q-Learning Optimization)")


    env = QoEEnvironment()
    n_states = 5
    n_actions = 3

    Q = np.zeros((n_states, n_actions))

    alpha = 0.1
    gamma = 0.95
    epsilon = 1.0
    epsilon_decay = 0.995
    epsilon_min = 0.01

    rewards_history = []

    for episode in range(episodes):
        state = env.reset()
        total_reward = 0

        for step in range(50):
            if np.random.random() < epsilon:
                action = np.random.randint(n_actions)
            else:
                action = np.argmax(Q[state])

            next_state, reward, done = env.step(action)

            Q[state, action] = Q[state, action] + alpha * (
                reward + gamma * np.max(Q[next_state]) - Q[state, action]
            )

            state = next_state
            total_reward += reward

            if done:
                break

        rewards_history.append(total_reward)
        epsilon = max(epsilon_min, epsilon * epsilon_decay)

        if (episode + 1) % 100 == 0:
            print(f"Episode {episode + 1}/{episodes}, Avg Reward: {np.mean(rewards_history[-100:]):.3f}")

    print("\nOptimal Q-Table:")
    print(Q)
    print("\nOptimal Policy (best action per state):")
    policy = np.argmax(Q, axis=1)
    print(policy)

    plt.figure(figsize=(10, 6))
    plt.plot(np.convolve(rewards_history, np.ones(50)/50, mode='valid'))
    plt.xlabel('Episode')
    plt.ylabel('Average Reward (50-episode window)')
    plt.title('Q-Learning: Reward Progress')
    plt.tight_layout()
    plt.show()

    return Q, policy

